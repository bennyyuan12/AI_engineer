from pydantic import BaseModel, Field
from typing import Optional

class RAGRequest(BaseModel):
    query: str = Field(..., description="The query to be answered using the RAG pipeline.")

class RAGUsedContext(BaseModel):
    image_url: str = Field(..., description ='The URL of the image of the item')
    price: Optional[float] = Field(..., description = 'The price of the item')
    description: str = Field(..., description='the descriptin of the item')

class RAGResponse(BaseModel):
    request_id: str = Field(..., description = 'The request Id')
    answer: str = Field(..., description="The answer generated by the RAG pipeline based on the provided query.")
    used_context: list[RAGUsedContext] = Field(..., description='information about the items used ot answer the query')